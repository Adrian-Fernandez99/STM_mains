void HAL_I2C_ErrorCallback(I2C_HandleTypeDef *I2cHandle) {
/** Error_Handler() function is called when error occurs.
* 1- When Slave doesn't acknowledge its address, Master restarts communication.
* 2- When Master doesn't acknowledge the last data transferred, Slave doesn't*/
	if (HAL_I2C_GetError(I2cHandle) != HAL_I2C_ERROR_AF) {
		// En lugar de Error_Handler(), reiniciamos el periférico para limpiar el estado de error
		HAL_I2C_DeInit(I2cHandle);
		HAL_I2C_Init(I2cHandle);
	}

	// Volvemos a poner el esclavo en modo de escucha tras el error
	HAL_I2C_EnableListen_IT(I2cHandle);
}

